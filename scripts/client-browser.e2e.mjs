import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { chromium } from "/tmp/auth-browser/node_modules/playwright/index.mjs";
const browser=await chromium.launch({headless:true});
try{
 const context=await browser.newContext({baseURL:"http://127.0.0.1:4174"});
 const page=await context.newPage();
 const terms=await (await context.request.get("/api/public/terms")).json();
 const email="client-browser-"+randomUUID()+"@example.test";
 const password="StrongBrowser-"+randomUUID();
 await page.goto("/register");
 await page.locator('input').nth(0).fill("Client");
 await page.locator('input').nth(1).fill("Browser");
 await page.locator('input[type=email]').fill(email);
 await page.locator('input[type=password]').fill(password);
 await page.locator('input[type=checkbox]').check();
 await page.getByRole("button",{name:"Create account"}).click();
 await page.waitForURL("**/login");
 await page.locator("#email").fill(email);
 await page.locator("#password").fill(password);
 await page.getByRole("button",{name:"Sign In",exact:true}).click();
 await page.waitForURL(url=>!url.pathname.endsWith("/login"));
 await page.goto("/client/profile");
 await page.getByRole("heading",{name:"My Profile"}).waitFor();
 await page.getByRole("heading",{name:"Service addresses"}).waitFor();
 const form=page.locator("form").last();
 await form.locator("input").nth(0).fill("Home");
 await form.locator("input").nth(1).fill("123 Test St");
 await form.locator("input").nth(2).fill("Atlanta");
 await form.locator("input").nth(3).fill("GA");
 await form.locator("input").nth(4).fill("30301");
 await form.getByRole("button",{name:"Add address"}).click();
 await page.getByText("123 Test St, Atlanta, GA 30301").waitFor();
 await page.goto("/client/service-requests");
 await page.getByRole("heading",{name:"My Service Requests"}).waitFor();
 await page.locator("#serviceAddress").fill("123 Test St");
 await page.locator("#city").fill("Atlanta");
 await page.locator("#state").fill("GA");
 await page.locator("#zip").fill("30301");
 await page.locator("#description").fill("Test gate repair");
 await page.getByRole("button",{name:"Submit request"}).click();
 await page.getByText("Service request submitted").waitFor();
 await page.goto("/request-service");
 await page.getByRole("heading",{name:"Request Gate or Landscape Service"}).waitFor();
 console.log("Client registration, address CRUD, service request, and guest intake browser smoke passed");
 await context.close();
}finally{await browser.close();}
